"""Write the shared examples as a C/C++ header of test vectors for the firmware.

    uv run python -m iot_backend.vectors           # (re)write tests/generated/test_vectors.h
    uv run python -m iot_backend.vectors --check   # exit 1 if the header is out of date

The header is generated from tests/protocol-examples/*.json (radio frames) and
tests/serial-examples/*.json (serial lines). It is plain C99 that C++ also accepts: fixed
arrays and structs, no allocation, no library beyond <stdint.h> and <stddef.h>, so the
firmware's unit tests (on the laptop or on the board) can include it directly. A test in
backend/tests keeps it identical to what this script writes.

What the firmware must do with it:

* every valid frame: decode `bytes` to the header fields listed (and the payload described in
  `fields_json`), and encode those fields back to exactly `bytes`;
* every invalid frame: refuse it with `reject_reason`, without crashing;
* every serial line with `downlink` 1: C's parser must give `result` (and `reason`), and for a
  message the `type` and `fields` listed;
* every serial line with `downlink` 0: lines C writes must look exactly like the valid ones
  (C's encoder writes the keys in the same order, without spaces, CRC in upper-case hex).
"""

import argparse
import json
import sys
from pathlib import Path

from iot_backend.protocol import MessageType
from iot_backend.transports.serial_format import (
    MAX_DOWN_LINE,
    MAX_TX_PAYLOAD,
    MAX_UP_LINE,
    SERIAL_VERSION,
    crc16,
)

ROOT = Path(__file__).resolve().parents[3]
PROTOCOL_EXAMPLES = ROOT / "tests" / "protocol-examples"
SERIAL_EXAMPLES = ROOT / "tests" / "serial-examples"
OUTPUT = ROOT / "tests" / "generated" / "test_vectors.h"


def _c_string(data: bytes) -> str:
    """A C string literal for arbitrary bytes. Octal escapes (fixed 3 digits) so that a
    following hex digit can never extend an escape; '?' escaped to rule out trigraphs."""
    out = []
    for byte in data:
        ch = chr(byte)
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif ch == "?":
            out.append("\\?")
        elif 32 <= byte < 127:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def _bytes_array(name: str, data: bytes) -> str:
    if not data:
        return f"static const uint8_t {name}[1] = {{0}};  /* empty */"
    items = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{items}}};"


def _frame_vectors() -> tuple[list[str], list[str]]:
    arrays, rows = [], []
    for i, path in enumerate(sorted(PROTOCOL_EXAMPLES.glob("*.json"))):
        case = json.loads(path.read_text(encoding="utf-8"))
        data = bytes.fromhex(case["hex"])
        arrays.append(_bytes_array(f"iot_frame_bytes_{i}", data))
        if case["valid"]:
            f = case["frame"]
            header = (
                f"{f['version']}, 0x{MessageType[f['type']]:02x}, {f['src']}, {f['dst']}, "
                f"{f['session']}u, {f['seq']}u, {f['ttl']}, {data[13]}"
            )
            fields = json.dumps(f, separators=(",", ":")).encode("ascii")
            reason = b""
        else:
            header = "0, 0, 0, 0, 0u, 0u, 0, 0"
            fields = b""
            reason = case["reject_reason"].encode("ascii")
        rows.append(
            f"    {{{_c_string(case['name'].encode('ascii'))}, iot_frame_bytes_{i}, {len(data)}, "
            f"{1 if case['valid'] else 0}, {_c_string(reason)}, {header}, {_c_string(fields)}}},"
        )
    return arrays, rows


def _serial_vectors() -> list[str]:
    rows = []
    for path in sorted(SERIAL_EXAMPLES.glob("*.json")):
        case = json.loads(path.read_text(encoding="utf-8"))
        line = (
            bytes.fromhex(case["line_hex"]) if "line_hex" in case else case["line"].encode("ascii")
        )
        fields = case.get("fields", {})
        pairs = ";".join(f"{k}={v}" for k, v in fields.items() if k not in ("v", "t"))
        rows.append(
            "    {"
            + ", ".join(
                [
                    _c_string(case["name"].encode("ascii")),
                    "1" if case["direction"] == "down" else "0",
                    _c_string(line),
                    str(len(line)),
                    _c_string(case["result"].encode("ascii")),
                    _c_string(case.get("reason", "").encode("ascii")),
                    _c_string(str(fields.get("t", "")).encode("ascii")),
                    _c_string(pairs.encode("ascii")),
                ]
            )
            + "},"
        )
    return rows


def generate() -> str:
    arrays, frame_rows = _frame_vectors()
    serial_rows = _serial_vectors()
    parts = [
        "/* GENERATED by `uv run python -m iot_backend.vectors` (backend/) from",
        " * tests/protocol-examples/ and tests/serial-examples/. Do not edit by hand:",
        " * change the examples and run the generator. Draft, pending Dev's review. */",
        "#ifndef IOT_TEST_VECTORS_H",
        "#define IOT_TEST_VECTORS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "/* ---- serial line constants (docs/SERIAL_PROTOCOL.md) ---- */",
        f"#define IOT_SERIAL_VERSION {SERIAL_VERSION}",
        f"#define IOT_SERIAL_MAX_DOWN_LINE {MAX_DOWN_LINE} /* bytes, newline included */",
        f"#define IOT_SERIAL_MAX_UP_LINE {MAX_UP_LINE}",
        f"#define IOT_SERIAL_MAX_TX_PAYLOAD {MAX_TX_PAYLOAD}",
        '#define IOT_SERIAL_CRC_CHECK_INPUT "123456789"',
        f"#define IOT_SERIAL_CRC_CHECK_VALUE 0x{crc16(b'123456789'):04X}u /* CRC-16/CCITT-FALSE */",
        "",
        "/* ---- radio frames (docs/PROTOCOL.md) ---- */",
        "typedef struct {",
        "    const char *name;",
        "    const uint8_t *bytes;",
        "    size_t len;",
        "    int valid;                 /* 1: decode to these fields and encode back to bytes */",
        '    const char *reject_reason; /* for invalid frames, else "" */',
        "    uint8_t version, type, src, dst;",
        "    uint32_t session, seq;",
        "    uint8_t ttl, payload_len;",
        "    const char *fields_json;   /* the whole expected frame, payload included */",
        "} iot_frame_vector;",
        "",
        *arrays,
        "",
        "static const iot_frame_vector IOT_FRAME_VECTORS[] = {",
        *frame_rows,
        "};",
        f"#define IOT_FRAME_VECTOR_COUNT {len(frame_rows)}",
        "",
        "/* ---- serial lines (docs/SERIAL_PROTOCOL.md) ---- */",
        "typedef struct {",
        "    const char *name;",
        "    int downlink;        /* 1: laptop to C (C parses it); 0: C to laptop (C writes it) */",
        "    const char *line;    /* the line without its newline */",
        "    size_t len;",
        '    const char *result;  /* "message", "log", "noise" or "rejected" */',
        '    const char *reason;  /* for "rejected" */',
        '    const char *type;    /* for "message": hb, ack, rs, tx, fr, st, ... */',
        '    const char *fields;  /* for "message": key=value;key=value as on the wire */',
        "} iot_serial_vector;",
        "",
        "static const iot_serial_vector IOT_SERIAL_VECTORS[] = {",
        *serial_rows,
        "};",
        f"#define IOT_SERIAL_VECTOR_COUNT {len(serial_rows)}",
        "",
        "#endif /* IOT_TEST_VECTORS_H */",
        "",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the firmware test vectors header.")
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != text:
            print(f"{OUTPUT} is out of date: run `uv run python -m iot_backend.vectors`")
            return 1
        print(f"{OUTPUT} is up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with OUTPUT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
